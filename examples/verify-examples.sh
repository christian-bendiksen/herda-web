WHY_400="$(env -u MALM_USER_OVERLAY_DIR HOME="$HOME5" XDG_CONFIG_HOME="$XDG5" XDG_STATE_HOME="$STATE5" XDG_CACHE_HOME="$CACHE5" \
  "$MALM_BIN" why herda_compositor.outer_gap --source "$PACK5" --format json)"

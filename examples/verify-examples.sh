#!/usr/bin/env bash
# End-to-end live verification of documented Malm 3 syntax, module composition,
# ~/.config/malm/ Tier 3 user overlays, override precedence, and legacy rejections
# against the real `malm` 0.4.1 binary.
#
# Usage:
#   ./examples/verify-examples.sh
#   MALM_BIN=/path/to/malm ./examples/verify-examples.sh

set -euo pipefail

MALM_BIN="${MALM_BIN:-/home/christian/Development/malm-herda/target/release/malm}"

if [[ ! -x "$MALM_BIN" ]]; then
  echo "ERROR: malm binary not found or not executable at: $MALM_BIN" >&2
  exit 1
fi

TMP_ROOT="$(mktemp -d /tmp/malm-website-verify-XXXXXX)"
chmod 700 "$TMP_ROOT"
trap 'rm -rf "$TMP_ROOT"' EXIT

PASS_COUNT=0
pass() {
  PASS_COUNT=$((PASS_COUNT + 1))
  printf '[PASS %02d] %s\n' "$PASS_COUNT" "$1"
}

fail() {
  printf '[FAIL] %s\n' "$1" >&2
  exit 1
}

# Isolate from host user overlays and host state store by default
export MALM_USER_OVERLAY_DIR=""
export MALM_OS_FACTS_PATH="$TMP_ROOT/nonexistent-os-facts.json"

VERSION_OUT="$("$MALM_BIN" --version)"
echo "Verifying against: $VERSION_OUT"
[[ "$VERSION_OUT" == *"0.4.1"* ]] || fail "Expected malm 0.4.1, got: $VERSION_OUT"
pass "Binary version verified ($VERSION_OUT)"

# -----------------------------------------------------------------------------
# 1. Starter Pack + External .tpl Template (source check + source render)
# -----------------------------------------------------------------------------
PACK1="$TMP_ROOT/pack1"
mkdir -p "$PACK1/malm/modules/terminal"

cat > "$PACK1/malm.malm" << 'EOF'
malm 3
authority user

pack "dev.example.desk" {
    target: "~/.config",
    default_profile: "default",
}

import "malm/modules/terminal/terminal.malm"

profile "default" {
    terminal.font_size = 11.5
}
EOF

cat > "$PACK1/malm/modules/terminal/terminal.malm" << 'EOF'
malm 3

module terminal {
    doc "Terminal emulator theme and font settings"
    option font_family: string = "JetBrains Mono"
    option font_size: float(8.0..=24.0) = 11.0
    option accent: color = "#4DA3FF"

    render "terminal/theme.conf" as tpl("malm/modules/terminal/theme.tpl") {
        font: font_family,
        size: font_size,
        accent_hex: accent.hex(),
        accent_soft: accent.lighten(0.12).hex(),
    }
}
EOF

cat > "$PACK1/malm/modules/terminal/theme.tpl" << 'EOF'
{# Generated by Malm 3 #}
font_family = {{ font }}
font_size = {{ size }}
accent = {{ accent_hex }}
accent_soft = {{ accent_soft }}
EOF

"$MALM_BIN" source check --source "$PACK1" --plain >/dev/null
"$MALM_BIN" source render --source "$PACK1" --profile default --output "$TMP_ROOT/render1" --plain >/dev/null
grep -q "font_family = JetBrains Mono" "$TMP_ROOT/render1/.config/terminal/theme.conf" || fail "Missing rendered font_family"
grep -q "font_size = 11.5" "$TMP_ROOT/render1/.config/terminal/theme.conf" || fail "Missing profile font_size 11.5"
grep -q "accent = #4da3ff" "$TMP_ROOT/render1/.config/terminal/theme.conf" || fail "Missing rendered accent color"
pass "Starter pack + .tpl template (source check & source render)"

# -----------------------------------------------------------------------------
# 2. Core Malm 3 Language: Types, Refinements, Match, Option/Result, Stdlib, Multi-Format Renders
# -----------------------------------------------------------------------------
PACK2="$TMP_ROOT/pack2"
mkdir -p "$PACK2"

cat > "$PACK2/malm.malm" << 'EOF'
malm 3
authority user

pack "dev.malm.langcheck" {
    target: "~/.config",
    default_profile: "default",
}

struct WindowMargins {
    outer: int(0..=64) = 8,
    inner: int(0..=64) = 4,
} where {
    inner <= outer
}

enum PaceMode {
    Normal,
    Quiet { minutes: int(5..=240) },
}

fn pace_label(m: PaceMode) -> string {
    match m {
        PaceMode::Normal => "normal",
        PaceMode::Quiet { minutes } if minutes >= 60 => format!("deep-{}m", minutes),
        PaceMode::Quiet { minutes } => format!("quiet-{}m", minutes),
    }
}

module core_demo {
    option margins: WindowMargins = { outer: 12, inner: 6 }
    option optional_note: Option<string> = None
    option accent: color = "#4DA3FF"
    option raw_regex: string = r#"^[a-z0-9_]+$"#
    option mask: int = 0o755
    option flags: int = 0b1010_0101
    option hex_val: int = 0xFF

    let label = pace_label(PaceMode::Quiet { minutes: 90 })
    let quoted = shell.quote("hello world")
    let rounded = math.round(3.7)
    let joined = path.join(["home", "demo", "config.json"])
    let digest = hash.sha256("malm3")
    let parsed_ok = json.parse("{\"ok\":true}").is_ok()
    let safe_color = accent.darken(0.1).hex()
    let items = [for n in 1..=4 if n % 2 == 0 { n * 10 }]

    render "demo/out.json" as json {
        {
            label: label,
            quoted: quoted,
            rounded: rounded,
            joined: joined,
            digest_len: digest.len(),
            parsed_ok: parsed_ok,
            safe_color: safe_color,
            items: items,
            mask: mask,
            flags: flags,
            hex_val: hex_val,
            raw_regex: raw_regex,
            optional_note: optional_note,
        }
    }

    render "demo/out.toml" as toml {
        {
            margins: margins,
            optional_note: optional_note,
        }
    }

    render "demo/out.kdl" as kdl {
        window(outer: margins.outer, inner: margins.inner, note: optional_note)
    }

    render "demo/out.ini" as ini {
        {
            general: {
                label: label,
                optional_note: optional_note,
            }
        }
    }

    render "demo/out.text" as text {
        """
        label=${label}
        color=${safe_color}
        """
    }
}

profile "default" { }
EOF

"$MALM_BIN" source check --source "$PACK2" --plain >/dev/null
"$MALM_BIN" source render --source "$PACK2" --profile default --output "$TMP_ROOT/render2" --plain >/dev/null
grep -q '"label": "deep-90m"' "$TMP_ROOT/render2/.config/demo/out.json" || fail "Missing match/format! output in JSON"
grep -q '"optional_note": null' "$TMP_ROOT/render2/.config/demo/out.json" || fail "Option None should serialize as null in JSON"
! grep -q 'optional_note' "$TMP_ROOT/render2/.config/demo/out.toml" || fail "Option None should omit in TOML"
! grep -q 'note=' "$TMP_ROOT/render2/.config/demo/out.kdl" || fail "Option None should omit in KDL"
pass "Core Malm 3 syntax, refinements, match, Option/Result, stdlib & multi-format renders"

# -----------------------------------------------------------------------------
# 3. Multi-File Module Composition (pub mod / pub use / slot / impl + E016 & E001)
# -----------------------------------------------------------------------------
PACK3="$TMP_ROOT/pack3"
mkdir -p "$PACK3/malm/modules/compositor"

cat > "$PACK3/malm.malm" << 'EOF'
malm 3
authority user

pack "dev.malm.modules" {
    target: "~/.config",
    default_profile: "default",
}

import "malm/mod.malm"
import "malm/modules/compositor/compositor.malm"

profile "default" { }
EOF

cat > "$PACK3/malm/mod.malm" << 'EOF'
malm 3
pub mod contracts;
pub use crate::contracts::{compositor, format_tag};
EOF

cat > "$PACK3/malm/contracts.malm" << 'EOF'
malm 3

pub slot compositor max = 1 {
    option layout: string
}

fn secret_helper(s: string) -> string {
    s.trim()
}

pub fn format_tag(s: string) -> string {
    secret_helper(s).upper()
}
EOF

cat > "$PACK3/malm/modules/compositor/compositor.malm" << 'EOF'
malm 3

module herda_compositor {
    impl compositor;
    option layout: string = "stage"
    option tag: string = format_tag("  lysrom  ")

    render "compositor/meta.json" as json {
        { layout: layout, tag: tag }
    }
}
EOF

"$MALM_BIN" source check --source "$PACK3" --plain >/dev/null
pass "Multi-file pub mod / pub use crate::... + slot/impl composition"

# E016 private visibility check
PACK3_E016="$TMP_ROOT/pack3-e016"
cp -R "$PACK3" "$PACK3_E016"
cat > "$PACK3_E016/malm/mod.malm" << 'EOF'
malm 3
pub mod contracts;
pub use crate::contracts::secret_helper;
EOF
if E016_OUT="$("$MALM_BIN" source check --source "$PACK3_E016" --plain 2>&1)"; then
  fail "Expected E016 private visibility error to fail"
fi
echo "$E016_OUT" | grep -q "E016" || fail "Expected E016 diagnostic, got: $E016_OUT"
pass "Private symbol import rejected with E016"

# E001 Tarjan SCC cycle detection
PACK3_E001="$TMP_ROOT/pack3-e001"
mkdir -p "$PACK3_E001"
cat > "$PACK3_E001/malm.malm" << 'EOF'
malm 3
authority user
pack "dev.malm.cycle" { target: "~/.config", default_profile: "default" }
module a { option x: int = b.y + 1 }
module b { option y: int = a.x + 1 }
profile "default" { }
EOF
if E001_OUT="$("$MALM_BIN" source check --source "$PACK3_E001" --plain 2>&1)"; then
  fail "Expected E001 cyclic dependency error to fail"
fi
echo "$E001_OUT" | grep -q "E001" || fail "Expected E001 diagnostic, got: $E001_OUT"
pass "Option dependency cycle rejected with E001"

# -----------------------------------------------------------------------------
# 4. authority os: Parameterized Modules, slots.*, Tier 1/2 Overlays & export fact
# -----------------------------------------------------------------------------
PACK4="$TMP_ROOT/pack4-os"
mkdir -p "$PACK4"
cat > "$PACK4/malm.malm" << 'EOF'
malm 3
authority os

pub slot kernel(min: 1, max: 1) {
    pub pkg: string,
    pub cmdline: List<string> = [],
}

pub module kernel(pkg: string = "linux") impl slot kernel {
    pub pkg = pkg
    pub cmdline = ["quiet", "splash"]
    packages.push(pkg)
}

pub module boot_meta {
    export fact "kernel_pkg" = slots.kernel.pkg
}

overlay package "gtk4" {
    source = {
        url: "https://download.gnome.org/sources/gtk/4.18/gtk-4.18.0.tar.xz",
        sha256: "0000pinned",
    }
    patches = [
        { path: "patches/gtk4-csd.patch", sha256: "1111pinned" },
    ]
    build = BuildSystem::Meson {
        flags: ["-Dwayland-backend=true"],
    }
    abi_gate = { soname: "libgtk-4.so.1", require_compat: true }
    staging = StagingMode::SideBySide
}

system release {
    use kernel("linux");
    use boot_meta();
    hostname = "herda-base"
    systemd::service "herda-session" {
        description = "Herda Session Service"
        exec_start = "/usr/bin/herda-session"
    }
    tmpfile "herda-run" {
        line = "d /run/herda 0755 root root -"
    }
}

system live overlay release {
    use kernel("linux-zen");
    hostname = "verksted"
    packages.extend(["ripgrep", "fd"])
    export fact "gpu_vendor" = "amd"
}
EOF

"$MALM_BIN" source check --source "$PACK4" --plain >/dev/null
pass "authority os parameterized module, slots.*, Tier 1/2 overlays & export fact"

# -----------------------------------------------------------------------------
# 5. Real ~/.config/malm/ Tier 3 User Overlays + Precedence + Full Plan/Apply/Resolve
# -----------------------------------------------------------------------------
PACK5="$TMP_ROOT/pack5"
XDG5="$TMP_ROOT/xdg5"
OVR_BARE="$TMP_ROOT/ovr-bare"
HOME5="$TMP_ROOT/home5"
STATE5="$TMP_ROOT/state5"
CACHE5="$TMP_ROOT/cache5"

mkdir -p "$PACK5" "$XDG5/malm" "$OVR_BARE" "$HOME5/.config" "$STATE5" "$CACHE5"
chmod 700 "$XDG5" "$XDG5/malm" "$OVR_BARE" "$HOME5" "$HOME5/.config" "$STATE5" "$CACHE5"

cat > "$PACK5/malm.malm" << 'EOF'
malm 3
authority user

pack "dev.malm.overrides" {
    target: "~/.config",
    default_profile: "default",
}

pub slot notifications max = 1 {
    option timeout: int
}

module herda_compositor {
    option outer_gap: int(0..=64) = 8
    option binds: Map<string, string> = {
        "close": "SUPER+w",
        "help": "SUPER+F1",
        "quit": "SUPER+Shift+q",
    }

    render "herda-compositor/config.json" as json {
        {
            outer_gap: outer_gap,
            binds: binds,
            input: { repeat_rate: 25 },

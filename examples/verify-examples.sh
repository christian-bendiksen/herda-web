# Banned syntax checks: bare hex color, ?, |>, null
check_rejected() {
  local name="$1"
  local body="$2"
  local dir="$TMP_ROOT/banned-$name"
  mkdir -p "$dir"
  printf '%s\n' "$body" > "$dir/malm.malm"
  if "$MALM_BIN" source check --source "$dir" --plain >/dev/null 2>&1; then
    fail "Expected banned syntax '$name' to be rejected"
  fi
}

check_rejected "bare-hex" 'malm 3
module m { option c: color = #1a1b26 }'
check_rejected "question-op" 'malm 3
fn f(x: Option<int>) -> Option<int> { Some(x?) }'
check_rejected "pipe-op" 'malm 3
let x = "hi" |> upper'
check_rejected "null-kw" 'malm 3
module m { option x: Option<string> = null }'
pass "Banned legacy syntax (#rrggbb, ?, |>, null) rejected by malm 0.4.1"

echo ""
echo "ALL $PASS_COUNT VERIFICATION CHECKS PASSED (exit 0)."
